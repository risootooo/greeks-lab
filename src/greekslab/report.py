"""Build the self-contained dark dashboard (docs/dashboard.html).

Two inline-SVG charts from a *real* chain: the OTM IV smile and the
dealer GEX-by-strike profile, plus case-study summary cards. No external
references of any kind -- the file works fully offline.
"""

from __future__ import annotations

import numpy as np
import pandas as pd


def _svg_line(xs, ys, w=860, h=300, color="#4cc9f0", xlabel="", ylabel=""):
    xs = np.asarray(xs, float); ys = np.asarray(ys, float)
    x0, x1 = xs.min(), xs.max(); y0, y1 = ys.min(), ys.max()
    ypad = (y1 - y0) * 0.12 or 1.0; y0 -= ypad; y1 += ypad
    px = 46; py = 26
    X = lambda v: px + (v - x0) / (x1 - x0) * (w - px - 14)
    Y = lambda v: h - py - (v - y0) / (y1 - y0) * (h - py - 12)
    pts = " ".join(f"{X(x):.1f},{Y(y):.1f}" for x, y in zip(xs, ys))
    dots = "".join(f'<circle cx="{X(x):.1f}" cy="{Y(y):.1f}" r="3" fill="{color}"/>'
                   for x, y in zip(xs, ys))
    grid = ""
    for frac in (0.0, 0.5, 1.0):
        yv = y0 + frac * (y1 - y0)
        grid += (f'<line x1="{px}" y1="{Y(yv):.1f}" x2="{w-14}" y2="{Y(yv):.1f}" '
                 f'stroke="#2a2f3a" stroke-width="1"/>'
                 f'<text x="4" y="{Y(yv)+4:.1f}" fill="#8b93a7" font-size="10">'
                 f'{yv:.3f}</text>')
    return (f'<svg viewBox="0 0 {w} {h}" width="100%" role="img">'
            f'<rect width="{w}" height="{h}" fill="#151924"/>'
            f'{grid}<polyline points="{pts}" fill="none" stroke="{color}" '
            f'stroke-width="2"/>{dots}'
            f'<text x="{w/2}" y="{h-4}" fill="#8b93a7" font-size="11" '
            f'text-anchor="middle">{xlabel}</text>'
            f'<text x="4" y="12" fill="#8b93a7" font-size="11">{ylabel}</text></svg>')


def _svg_bars(strikes, values, w=860, h=300):
    strikes = np.asarray(strikes, float); values = np.asarray(values, float)
    vmax = np.abs(values).max() or 1.0
    px = 46; py = 26
    bw = (w - px - 14) / len(strikes)
    mid = h / 2
    bars = ""
    for i, (k, v) in enumerate(zip(strikes, values)):
        bh = abs(v) / vmax * (h / 2 - py)
        y = mid - bh if v >= 0 else mid
        color = "#38d977" if v >= 0 else "#f0524f"
        bars += (f'<rect x="{px + i*bw + 1:.1f}" y="{y:.1f}" width="{bw-2:.1f}" '
                 f'height="{bh:.1f}" fill="{color}"><title>{k:.0f}: {v:,.0f}</title></rect>')
    labels = (f'<text x="4" y="{mid-4:.0f}" fill="#8b93a7" font-size="10">₹ Cr</text>'
              f'<text x="{px}" y="{h-4}" fill="#8b93a7" font-size="11">{strikes.min():.0f}</text>'
              f'<text x="{w-70}" y="{h-4}" fill="#8b93a7" font-size="11">{strikes.max():.0f}</text>')
    return (f'<svg viewBox="0 0 {w} {h}" width="100%" role="img">'
            f'<rect width="{w}" height="{h}" fill="#151924"/>'
            f'<line x1="{px}" y1="{mid}" x2="{w-14}" y2="{mid}" stroke="#3a4152"/>'
            f'{bars}{labels}</svg>')


def build_dashboard(smile_df, gex_df, cards, path, spot=None, title="GreeksLab — NIFTY Chain Analytics"):
    """cards: list of (heading, body_html). Charts show strikes within
    +/-8% of spot to keep bars readable."""
    smile_sorted = smile_df.sort_values("strike")
    smile_svg = _svg_line(smile_sorted["strike"].values,
                          smile_sorted["iv"].values * 100.0,
                          color="#4cc9f0", xlabel="Strike",
                          ylabel="Implied vol %")
    g = gex_df.copy()
    if spot:
        g = g[(g.index >= spot * 0.92) & (g.index <= spot * 1.08)]
    gex_svg = _svg_bars(g.index.values, g["gex_rs"].values / 1e7)
    card_html = "".join(
        f'<section class="card"><h3>{h}</h3><p>{b}</p></section>' for h, b in cards)
    html = f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>
 body{{background:#0e1117;color:#e6e9f0;font-family:Georgia,'Times New Roman',serif;margin:0;padding:32px}}
 h1{{font-size:28px;margin:0 0 4px}} h2{{color:#4cc9f0;font-size:19px;margin:28px 0 8px}}
 .sub{{color:#8b93a7;margin:0 0 8px}}
 .grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(250px,1fr));gap:14px}}
 .card{{background:#151924;border:1px solid #262c3d;border-radius:10px;padding:14px 16px}}
 .card h3{{margin:0 0 6px;font-size:15px;color:#ffd166}}
 .card p{{margin:0;font-size:14px;line-height:1.55;color:#c9cfdd}}
 .num{{color:#fff;font-weight:bold}}
 footer{{color:#8b93a7;font-size:12px;margin-top:30px;line-height:1.6}}
</style></head><body>
<h1>{title}</h1>
<p class="sub">Generated by GreeksLab from a real NSE bhavcopy chain. Fully offline, no external assets.</p>
<div class="grid">{card_html}</div>
<h2>Implied-volatility smile (OTM options)</h2>{smile_svg}
<h2>Dealer gamma exposure by strike (₹ crore, + = call gamma, − = put gamma)</h2>{gex_svg}
<footer>Method: Black-Scholes-Merton IV from exchange close premiums, r = 6.5%, q = 0,
actual/365. GEX convention and limitations are documented in the repository README.
Educational research software — not investment advice.</footer>
</body></html>"""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(html)
    return path
